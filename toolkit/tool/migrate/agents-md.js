#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const fsx = require('../lib/fsx');
const { resolvePaths } = require('../lib/paths');
const sync = require('../lib/sync');
const { starterAgentsMd } = require('../lib/projects');

const GENERATED_HEADER = '<!-- Generated by Toolkit';
const IMPORT_LINE = '@AGENTS.md\n';

function migrateOne(P, ctx, name, root, { dryRun }) {
  const claudeMdPath = `${root}/CLAUDE.md`;
  const agentsMdPath = `${root}/AGENTS.md`;
  const claudeMd = fsx.readText(claudeMdPath);
  const agentsMd = fsx.readText(agentsMdPath);
  const agentsMdGenerated = agentsMd != null && agentsMd.startsWith(GENERATED_HEADER);

  if (claudeMd === IMPORT_LINE) return 'untouched: already migrated';

  let nextAgentsMd = null; // null: leave AGENTS.md exactly as it is
  let summary;
  if (claudeMd != null) {
    if (agentsMd != null && !agentsMdGenerated && agentsMd !== claudeMd) {
      return 'refused: AGENTS.md is hand-written and differs from CLAUDE.md; resolve by hand';
    }
    nextAgentsMd = claudeMd;
    summary = 'moved CLAUDE.md to AGENTS.md';
  } else if (agentsMd == null) {
    nextAgentsMd = starterAgentsMd(name);
    summary = 'wrote starter AGENTS.md';
  } else {
    summary = 'added CLAUDE.md import line';
  }

  if (dryRun) return `would: ${summary}`;

  fsx.backupFile(P, claudeMdPath);
  fsx.backupFile(P, agentsMdPath);
  if (nextAgentsMd != null) fs.writeFileSync(agentsMdPath, nextAgentsMd);
  fs.writeFileSync(claudeMdPath, IMPORT_LINE);
  sync.syncProject(P, ctx, { root, quiet: true });
  return summary;
}

function migrate(P, ctx, { dryRun } = {}) {
  const results = [];
  for (const [name, p] of Object.entries(ctx.reg.projects)) {
    let did;
    try {
      did = migrateOne(P, ctx, name, p.path, { dryRun });
    } catch (e) {
      did = `error: ${e.message}`;
    }
    results.push({ name, did });
  }
  return results;
}

if (require.main === module) {
  const dryRun = process.argv.includes('--dry-run');
  const P = resolvePaths();
  const ctx = sync.loadContext(P);
  const results = migrate(P, ctx, { dryRun });
  for (const r of results) process.stdout.write(`${r.name}: ${r.did}\n`);
}

module.exports = { migrate };
