'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { parseFrontmatter } = require('./store');
const { norm } = require('./paths');

const MAX_DEPTH = 4;

function inlineImports(text, baseDir, home, depth = 0, warnings = []) {
  const out = [];
  let inFence = false;
  const lines = String(text).split(/\r?\n/);
  const endsWithNewline = /\n$/.test(text);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (i === lines.length - 1 && line === '' && endsWithNewline) continue;
    if (/^\s*```/.test(line)) { inFence = !inFence; out.push(line); continue; }
    const m = !inFence && /^\s*@(\S+)\s*$/.exec(line);
    if (!m) { out.push(line); continue; }
    let target = m[1];
    if (target.startsWith('~/')) target = path.join(home, target.slice(2));
    else if (!path.isAbsolute(target)) target = path.join(baseDir, target);
    target = norm(target);
    if (!fs.existsSync(target)) { warnings.push(`import not found: ${target}`); out.push(line); continue; }
    if (depth > MAX_DEPTH) { warnings.push(`import depth limit reached at ${target}`); out.push(line); continue; }
    const inner = inlineImports(fs.readFileSync(target, 'utf8'), path.dirname(target), home, depth + 1, warnings);
    out.push(inner.text);
  }
  let joined = out.join('\n');
  if (endsWithNewline && !joined.endsWith('\n')) joined += '\n';
  return { text: joined, warnings };
}

function stripFrontmatter(text) {
  return parseFrontmatter(text).body;
}

function trailParagraph(store = norm(path.resolve(__dirname, '..', '..'))) {
  const script = `${norm(store)}/hooks/trail/trail.js`;
  const commandPath = /\s/.test(script) ? `"${script}"` : script;
  return '## Toolkit trail\n\n' +
  'If no line starting with `Toolkit:` appeared when this session started, hooks are not ' +
  'running here. Then do two things yourself: at the start, read `.agents/trail.md` in the ' +
  'project if it exists and continue from what it says; and after each answer run `node ' +
  commandPath + ' note --asked "<what he asked, one line>" ' +
  '--answered "<what you did, one line>"`.';
}

function generateAgentsMd({ sources, claudeMd, packs, style, trail, store }) {
  const parts = [`<!-- Generated by Toolkit from: ${sources.join(', ')}. Edit those files, not this one. -->`];
  if (trail) parts.push(trailParagraph(store));
  const trimmed = (t) => String(t).replace(/\s+$/, '');
  if (claudeMd) parts.push(trimmed(claudeMd));
  for (const pack of packs || []) {
    parts.push(`## Rules: ${pack.name}`);
    for (const f of pack.files) parts.push(trimmed(f.text));
  }
  if (style) {
    parts.push('## Working style');
    parts.push(trimmed(stripFrontmatter(style.text)));
  }
  return parts.join('\n\n') + '\n';
}

function eventsOf(hook) {
  const m = hook.meta || {};
  return Array.isArray(m.events) && m.events.length ? m.events : m.event ? [m.event] : ['PreToolUse'];
}

function commandFor(hook, { claude = false } = {}) {
  const args = ((hook.meta && hook.meta.args) || []).map((a) => (/\s/.test(a) ? `"${a}"` : a));
  if (claude && hook.meta && hook.meta.runtime === 'bun') {
    const launcher = String(hook.script).replace(/\/[^/]+\/[^/]+$/, '/lib/guard-launch.sh');
    return [`/bin/sh "${launcher}" "${hook.script}"`, ...args].join(' ');
  }
  return [`node "${hook.script}"`, ...args].join(' ');
}

function hookEntryClaude(hook) {
  const entry = { hooks: [{ type: 'command', command: commandFor(hook, { claude: true }), timeout: hook.meta.timeout || 10 }] };
  if (hook.meta.matcher) entry.matcher = hook.meta.matcher;
  return entry;
}

function hookEntryCodex(hook) {
  if (hook.meta.codex === false) return null;
  const matcher = hook.meta.codex && hook.meta.codex.matcher ? hook.meta.codex.matcher : hook.meta.matcher;
  const entry = { hooks: [{ type: 'command', command: commandFor(hook), timeout: hook.meta.timeout || 10 }] };
  if (matcher) entry.matcher = matcher;
  return entry;
}

function generateHooksJson(hooks, sources) {
  const out = { description: `Generated by Toolkit from: ${sources.join(', ')}. Edit those, not this file.`, hooks: {} };
  for (const h of hooks) {
    const entry = hookEntryCodex(h);
    if (!entry) continue;
    for (const ev of eventsOf(h)) (out.hooks[ev] = out.hooks[ev] || []).push(entry);
  }
  return out;
}

function tomlStr(s) {
  return JSON.stringify(String(s)).replace(/\u007f/g, '\\u007f');
}

function mcpServerToml(name, server) {
  const key = (s) => /^[A-Za-z0-9_-]+$/.test(s) ? s : tomlStr(s);
  const table = `mcp_servers.${key(name)}`;
  const lines = [`[${table}]`];
  if (server.url) {
    lines.push(`url = ${tomlStr(server.url)}`);
    if (server.bearer_token_env_var) lines.push(`bearer_token_env_var = ${tomlStr(server.bearer_token_env_var)}`);
  } else {
    lines.push(`command = ${tomlStr(server.command)}`);
    if (server.args && server.args.length) lines.push(`args = [${server.args.map(tomlStr).join(', ')}]`);
    if (server.cwd) lines.push(`cwd = ${tomlStr(server.cwd)}`);
    if (server.env_vars) lines.push(`env_vars = [${server.env_vars.map(tomlStr).join(', ')}]`);
  }
  for (const field of ['enabled', 'required']) if (typeof server[field] === 'boolean') lines.push(`${field} = ${server[field]}`);
  for (const field of ['startup_timeout_sec', 'tool_timeout_sec']) if (Number.isFinite(server[field])) lines.push(`${field} = ${server[field]}`);
  for (const field of ['enabled_tools', 'disabled_tools']) if (Array.isArray(server[field])) lines.push(`${field} = [${server[field].map(tomlStr).join(', ')}]`);
  const tables = server.url ? { http_headers: server.http_headers || server.headers, env_http_headers: server.env_http_headers } : { env: server.env };
  for (const [suffix, values] of Object.entries(tables)) {
    if (!values || !Object.keys(values).length) continue;
    lines.push('', `[${table}.${suffix}]`);
    for (const [k, v] of Object.entries(values)) lines.push(`${suffix === 'http_headers' ? tomlStr(k) : key(k)} = ${tomlStr(v)}`);
  }
  return lines.join('\n') + '\n';
}

function generateCodexConfig({ mcp, sources }) {
  const parts = [`# Generated by Toolkit from: ${sources.join(', ')}. Edit those, not this file.\n`];
  for (const m of mcp) parts.push(mcpServerToml(m.name, m.server));
  return parts.join('\n');
}

function generateCodexRegion({ projectDocMaxBytes, projectDocFallbackFilenames, projects, mcp }) {
  const parts = [`project_doc_max_bytes = ${projectDocMaxBytes}\n`];
  if (projectDocFallbackFilenames) parts.push(`project_doc_fallback_filenames = [${projectDocFallbackFilenames.map(tomlStr).join(', ')}]\n`);
  for (const p of projects) {
    const value = String(p);
    const projectPath = /^(?:[a-z]:[\\/]|\\\\)/i.test(value) ? value.replace(/\//g, '\\') : value;
    parts.push(`[projects.${tomlStr(projectPath)}]\ntrust_level = "trusted"\n`);
  }
  for (const m of mcp) parts.push(mcpServerToml(m.name, m.server));
  return parts.join('\n');
}

function agentMdToToml(name, mdText, source) {
  const { data, body } = parseFrontmatter(mdText);
  const instructions = body.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"').replace(/\s+$/, '');
  return `# Generated by Toolkit from ${source}. Edit that, not this file.\n` +
    `name = ${tomlStr(data.name || name)}\n` +
    `description = ${tomlStr(data.description || name)}\n` +
    `developer_instructions = """\n${instructions}\n"""\n`;
}

function openaiYaml({ userOnly }) {
  return `policy:\n  allow_implicit_invocation: ${userOnly ? 'false' : 'true'}\n`;
}

module.exports = { inlineImports, stripFrontmatter, generateAgentsMd, eventsOf, commandFor, hookEntryClaude, hookEntryCodex, generateHooksJson, mcpServerToml, generateCodexConfig, generateCodexRegion, agentMdToToml, openaiYaml };
